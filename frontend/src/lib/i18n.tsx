export type Lang = 'th' | 'en'
const dictionaries: Record<Lang, Record<TKey, string>> = { en, th }
const LANG_KEY = 'hsmlis.lang'

type Translate = (key: TKey, values?: Record<string, string | number>) => string

type I18n = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: Translate
  /** Turns a thrown error into a message in the current language. */
  errorText: (error: unknown) => string
  /** A day ("2026-10-17") or an instant, as a date. Thai uses the Buddhist year: 17 ต.ค. 2569. */
  formatDate: (value: string) => string
  formatDateTime: (iso: string) => string
  /** Short, for labels: 17/10/69 14:05. */
  formatDateTimeShort: (iso: string) => string
  /** Day and month only, for chart axes. */
  formatDayShort: (day: string) => string
  /** Month and short year, for chart axes: ต.ค. 69 / Oct 26. */
  formatMonthShort: (day: string) => string
  formatNumber: (value: number) => string
  /** Short for axes: 12K, 1.5M (Thai: 1.2 หมื่น). */
  formatCompact: (value: number) => string
  /** Baht with two decimals: ฿1,250.00 */
  formatMoney: (value: number) => string
  /** A duration: 45 min, 2 h 10 min, 3 d 4 h. */
  formatMinutes: (minutes: number) => string
}

const I18nContext = createContext<I18n | null>(null)

function readLang(): Lang {
  try {
    return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'th'
  } catch {
    return 'th'
  }
}

const asDate = (value: string) => (value.length === 10 ? new Date(`${value}T00:00:00`) : new Date(value))

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)

  const setLang = useCallback((next: Lang) => {
    try {
      localStorage.setItem(LANG_KEY, next)
    } catch {
      // Private mode: the choice lasts for this visit.
    }
    document.documentElement.lang = next
    setLangState(next)
  }, [])

  const value = useMemo<I18n>(() => {
    const dict = dictionaries[lang]
    const t: Translate = (key, values) => (dict[key] ?? key).replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? ''))

    // Thai screens show the Buddhist year (2569), as Thai hospital paperwork does.
    const locale = lang === 'th' ? 'th-TH' : 'en-GB'
    const date = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric' })
    const dateTime = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' })
    const dateTimeShort = new Intl.DateTimeFormat(locale, { day: '2-digit', month: '2-digit', year: '2-digit', hour: '2-digit', minute: '2-digit' })
    const dayShort = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short' })
    const monthShort = new Intl.DateTimeFormat(locale, { month: 'short', year: '2-digit' })
    const number = new Intl.NumberFormat(locale, { maximumFractionDigits: 2 })
    const compact = new Intl.NumberFormat(locale, { notation: 'compact', maximumFractionDigits: 1 })
    const money = new Intl.NumberFormat(locale, { minimumFractionDigits: 2, maximumFractionDigits: 2 })
    const units = lang === 'th' ? { m: 'นาที', h: 'ชม.', d: 'วัน' } : { m: 'min', h: 'h', d: 'd' }

    return {
      lang,
      setLang,
      t,
      errorText: (error) => {
        if (error instanceof ApiError) {
          const code = error.code ?? ''
          const generic = code.endsWith('_code_taken') ? 'code_taken' : code.endsWith('_in_use') ? 'in_use' : code.endsWith('_not_found') ? 'not_found' : code
          for (const candidate of [code, generic]) {
            const key = `err.${candidate}` as TKey
            if (key in dict) return t(key)
          }
          return error.message
        }
        return error instanceof TypeError ? t('err.network') : String((error as Error)?.message ?? error)
      },
      formatDate: (v) => date.format(asDate(v)),
      formatDateTime: (iso) => dateTime.format(new Date(iso)),
      formatDateTimeShort: (iso) => dateTimeShort.format(new Date(iso)),
      formatDayShort: (day) => dayShort.format(asDate(day)),
      formatMonthShort: (day) => monthShort.format(asDate(day)),
      formatNumber: (n) => number.format(n),
      formatCompact: (n) => compact.format(n),
      formatMoney: (n) => `฿${money.format(n)}`,
      formatMinutes: (minutes) => {
        const m = Math.round(minutes)
        if (m < 60) return `${m} ${units.m}`
        if (m < 24 * 60) return `${Math.floor(m / 60)} ${units.h}${m % 60 ? ` ${m % 60} ${units.m}` : ''}`
        const h = Math.round(m / 60)
        return `${Math.floor(h / 24)} ${units.d}${h % 24 ? ` ${h % 24} ${units.h}` : ''}`
      },
    }
  }, [lang, setLang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18n {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
